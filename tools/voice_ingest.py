#!/usr/bin/env python3
"""Recorded System voice: plan recording waves, cut long takes into lines, wire them into a pack.

    python3 tools/voice_ingest.py plan   --pack <packDir> --voice <voiceDir>
    python3 tools/voice_ingest.py ingest <audio>... --wave V02 --pack <packDir> --voice <voiceDir>
                                  [--start 1] [--only id,id] [--who ty|klon] [--gap 1.6] [--partial] [--dry-run]
    python3 tools/voice_ingest.py status --pack <packDir> --voice <voiceDir>

The voice dir (per pack, e.g. the private repo's voice/) holds:
  waves.json   the plan: [{ "wave": "V01", "title": "...", "who": "ty|klon|oboje", "ids": [...]} |
               { ..., "categories": [...] } | { ..., "bosses": true }]  plus optional "say": { id: hint }
  WAVES.csv    generated: one row per line (wave, order, id, kind, category, who, scope, text, say, status)
  waves/V01.md generated reading script per wave (open it on the phone while recording)

plan     (re)builds WAVES.csv + waves/*.md from waves.json and the pack. Lines not in any wave land in the
         last wave "VNEW". Status of rows already recorded is kept. Re-run after editing quips or bosses.
ingest   One or more files. If every file name (stem) is a line id ("nat1_03.mp3"), each file is that line
         (single-file mode: retakes, ElevenLabs downloads). Otherwise the files are long takes read in
         script order: speech is split on silences >= --gap seconds; a CLAP (very short loud burst) throws
         away the line before it, so a fluffed line is fixed by clapping and reading it again. Segments map
         onto the wave's lines from --start (--each: every file is one line, files sorted by the ElevenLabs
         timestamp in their names, so downloads need no renaming) (or the --only ids, in that order). The segment count must
         match unless --partial. Every clip is trimmed, gets 0.12 s / 0.30 s of air, a high-pass, RMS
         levelling with a peak limit, and is written as <pack>/audio/<id>.mp3 (mono 96 kbps).
         Wiring: quip lines get "audio": "<id>.mp3" in quips.json; boss intro/defeat lines become quips
         (<boss>_intro / <boss>_defeat, categories boss_intro / boss_defeat) carrying the current text, so
         the engine plays the file whenever the boss line is spoken (matched by text; edit the text and it
         falls back to TTS until re-recorded). A waveform PNG (<voice>/_preview/<wave>.png) is always
         written; --dry-run writes nothing else.
status   Recorded / total per wave and minutes of audio.

Requires ffmpeg + numpy + Pillow.
"""
from __future__ import annotations

import argparse
import csv
import json
import re
import shutil
import subprocess
import sys
import tempfile
from datetime import date
from pathlib import Path

import numpy as np

SR = 44100
FRAME = 0.02  # analysis frame, seconds
CSV_COLS = ["wave", "order", "id", "kind", "category", "who", "scope", "text", "say", "status"]
WORDS_PER_SEC = 2.6  # rough reading speed for the length sanity check
# less mud, clearer consonants, a bit of air (dark phone-sample clones); tuned on the DCC clone, Nov 2026
EQ = "highpass=f=80,equalizer=f=250:t=q:w=1.2:g=-2,equalizer=f=3500:t=q:w=1.0:g=4,highshelf=f=9000:g=3,deesser=i=0.6:m=0.5:f=0.5:s=o"  # + de-esser: whispers were mostly sibilance

# Lines mentioning these are DCC-specific; everything else can go to the generic engine pack.
DCC_RE = re.compile(
    r"carl|donut|mordecai|borant|syndicate|princess|dinniman|crawler|dungeon crawler|katia|floor|sponsor"
    r"|bronze box|silver box|gold box|loot box|safe room|stairwell|porter|burbleton|quizmaster|babette"
    r"|mournwick|big tuesday", re.I)


def die(msg: str) -> None:
    print(f"error: {msg}", file=sys.stderr)
    sys.exit(2)


def load_json(p: Path, default=None):
    if not p.exists():
        return default
    return json.loads(p.read_text(encoding="utf-8"))


def save_json(p: Path, data) -> None:
    p.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def norm_key(text: str) -> str:
    """Same as the engine's voiceKey (server/pack-core.js)."""
    t = str(text or "").replace("‘", "'").replace("’", "'").replace("“", '"').replace("”", '"')
    return re.sub(r"[.!?…]+$", "", re.sub(r"\s+", " ", t).strip().lower())


# ---------------------------------------------------------------- pack lines

def pack_lines(pack: Path) -> dict:
    """id -> {id, kind, category, text}: every quip plus boss intro / defeat lines."""
    out = {}
    for q in load_json(pack / "quips.json", []) or []:
        if q.get("category") in ("boss_intro", "boss_defeat", "monster_intro", "npc_intro"):
            continue  # generated by this tool from bosses.json
        out[q["id"]] = {"id": q["id"], "kind": "quip", "category": q["category"], "text": q["text"].strip()}
    for b in load_json(pack / "bosses.json", []) or []:
        for field, suffix in (("intro", "intro"), ("defeatLine", "defeat")):
            t = (b.get(field) or "").strip()
            if t:
                lid = f"{b['id']}_{suffix}"
                out[lid] = {"id": lid, "kind": f"boss_{suffix}", "category": f"boss_{suffix}", "text": t}
    for fn, kind in (("monsters.json", "monster"), ("npcs.json", "npc")):
        for e in load_json(pack / fn, []) or []:
            t = (e.get("intro") or "").strip()
            if t and e.get("id"):
                lid = f"{e['id']}_intro"
                out[lid] = {"id": lid, "kind": f"{kind}_intro", "category": f"{kind}_intro", "text": t}
    return out


def read_csv(p: Path) -> list[dict]:
    if not p.exists():
        return []
    with p.open(encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def write_csv(p: Path, rows: list[dict]) -> None:
    with p.open("w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=CSV_COLS, quoting=csv.QUOTE_ALL)
        w.writeheader()
        for r in rows:
            w.writerow({k: r.get(k, "") for k in CSV_COLS})


# ---------------------------------------------------------------- plan

def cmd_plan(a) -> None:
    pack, vdir = Path(a.pack), Path(a.voice)
    spec = load_json(vdir / "waves.json")
    if not spec:
        die(f"{vdir / 'waves.json'} missing")
    lines = pack_lines(pack)
    old = {r["id"]: r for r in read_csv(vdir / "WAVES.csv")}
    say = spec.get("say", {})
    gloss = [(re.compile(rf"\b{re.escape(k)}\w*", re.I), k, v) for k, v in spec.get("glossary", {}).items()]

    def hint(text: str) -> str:
        hits = [f"{k} = {v}" for rx, k, v in gloss if rx.search(text)]
        return " · ".join(hits[:4])
    used, rows, waves = set(), [], []
    for w in spec["waves"]:
        ids = []
        if w.get("ids"):
            ids = [i for i in w["ids"] if i in lines]
            for i in w["ids"]:
                if i not in lines:
                    print(f"warn: {w['wave']}: unknown line id {i}")
        if w.get("categories"):
            ids += [l["id"] for l in lines.values() if l["category"] in w["categories"]]
        if w.get("bosses"):
            ids += [l["id"] for l in lines.values() if l["kind"].startswith("boss_")]
        if w.get("intros"):
            ids += [l["id"] for l in lines.values() if l["kind"] in ("monster_intro", "npc_intro")]
        ids = [i for i in dict.fromkeys(ids) if i not in used]
        used.update(ids)
        waves.append((w, ids))
    rest = [i for i in lines if i not in used]
    if rest:
        waves.append(({"wave": "VNEW", "title": "Nové / nezařazené hlášky", "who": "oboje"}, rest))
    for w, ids in waves:
        for n, i in enumerate(ids, 1):
            l = lines[i]
            prev = old.get(i, {})
            status = prev.get("status", "")
            if status and norm_key(prev.get("text", "")) != norm_key(l["text"]):
                status = "ZMĚNA TEXTU, nahrát znovu"
            rows.append({
                "wave": w["wave"], "order": n, "id": i, "kind": l["kind"], "category": l["category"],
                "who": w.get("who", "oboje"), "scope": "dcc" if DCC_RE.search(l["text"]) else "generic",
                "text": l["text"], "say": " · ".join(x for x in (say.get(i, ""), hint(l["text"])) if x), "status": status,
            })
    write_csv(vdir / "WAVES.csv", rows)
    wdir = vdir / "waves"
    wdir.mkdir(parents=True, exist_ok=True)
    for f in wdir.glob("V*.md"):
        f.unlink()
    for w, ids in waves:
        wr = [r for r in rows if r["wave"] == w["wave"]]
        if not wr:
            continue
        write_script(wdir / f"{w['wave']}.md", w, wr)
    print(f"plan: {len(rows)} lines in {len(waves)} waves -> {vdir / 'WAVES.csv'}, {wdir}/")
    for w, ids in waves:
        secs = sum(est_secs(lines[i]["text"]) for i in ids)
        print(f"  {w['wave']:5} {len(ids):3} lines  ~{secs / 60:4.1f} min  {w.get('title', '')}")


def est_secs(text: str) -> float:
    return max(0.6, len(text.split()) / WORDS_PER_SEC)


def write_script(p: Path, w: dict, rows: list[dict]) -> None:
    who = {"ty": "namluvíš ty", "klon": "klon hlasu (ElevenLabs)", "oboje": "ty nebo klon"}.get(w.get("who"), "")
    mins = sum(est_secs(r["text"]) for r in rows) / 60
    out = [f"# {w['wave']} · {w.get('title', '')}", "",
           f"**{len(rows)} hlášek · čistého textu ~{mins:.1f} min · {who}**", ""]
    if w.get("note"):
        out += [w["note"], ""]
    out += ["Čti v tomhle pořadí. Mezi hláškami **2–3 s ticho**, uvnitř hlášky pauza max ~1 s.",
            "Přeřekl ses? **Tleskni** a řekni celou hlášku znovu. Číslo nečti.", ""]
    for r in rows:
        tag = " · *DCC*" if r["scope"] == "dcc" else ""
        done = " ✅" if r["status"] and not r["status"].startswith("ZMĚNA") else ""
        out.append(f"**{r['order']}.** `{r['id']}`{tag}{done}  ")
        out.append(f"{r['text']}  ")
        if r["say"]:
            out.append(f"🗣 *{r['say']}*  ")
        out.append("")
    p.write_text("\n".join(out), encoding="utf-8")


# ---------------------------------------------------------------- audio helpers

def ffmpeg() -> str:
    exe = shutil.which("ffmpeg")
    if not exe:
        die("ffmpeg not found")
    return exe


def decode(path: Path) -> np.ndarray:
    r = subprocess.run([ffmpeg(), "-v", "error", "-i", str(path), "-ac", "1", "-ar", str(SR), "-f", "f32le", "-"],
                       capture_output=True)
    if r.returncode:
        die(f"cannot decode {path}: {r.stderr.decode(errors='replace')[:300]}")
    return np.frombuffer(r.stdout, dtype=np.float32).copy()


def frames_db(x: np.ndarray) -> np.ndarray:
    n = int(SR * FRAME)
    m = len(x) // n
    if m == 0:
        return np.array([-100.0])
    f = x[: m * n].reshape(m, n)
    rms = np.sqrt(np.mean(f * f, axis=1) + 1e-12)
    return 20 * np.log10(rms + 1e-9)


def detect(x: np.ndarray, gap: float) -> tuple[list[dict], float]:
    """Speech segments and claps [{s, e, clap}] in time order (seconds), speech split on silences >= gap."""
    db = frames_db(x)
    live = db[db > -90] if np.any(db > -90) else db  # ignore digital silence when finding the room noise
    floor = float(np.percentile(live, 15))
    loud = float(np.percentile(live, 97))
    thr = max(-60.0, floor + 0.3 * (loud - floor), floor + 10)
    on = db > thr
    runs, i, n = [], 0, len(on)
    while i < n:
        if on[i]:
            j = i
            while j < n and on[j]:
                j += 1
            runs.append([i, j])
            i = j
        else:
            i += 1
    top = float(np.max(np.abs(x))) if len(x) else 0.0
    iso = int(0.35 / FRAME)
    claps = set()
    for k, (s, e) in enumerate(runs):
        left = s - runs[k - 1][1] if k else iso
        right = runs[k + 1][0] - e if k + 1 < len(runs) else iso
        if (e - s) * FRAME <= 0.25 and left >= iso and right >= iso and is_clap(x, s, e, top):
            claps.add(k)
    out, cur = [], None
    gap_f = int(gap / FRAME)
    for k, (s, e) in enumerate(runs):
        if k in claps:
            if cur:
                out.append(cur)
                cur = None
            out.append({"s": s * FRAME, "e": e * FRAME, "clap": True})
            continue
        if cur and s - int(cur["e"] / FRAME) < gap_f:
            cur["e"] = e * FRAME
        else:
            if cur:
                out.append(cur)
            cur = {"s": s * FRAME, "e": e * FRAME, "clap": False}
    if cur:
        out.append(cur)
    return [sg for sg in out if sg["clap"] or sg["e"] - sg["s"] >= 0.25], thr


def is_clap(x: np.ndarray, s: int, e: int, top: float) -> bool:
    seg = x[int(s * FRAME * SR): int(e * FRAME * SR)]
    if not len(seg) or top <= 0:
        return False
    peak = float(np.max(np.abs(seg)))
    rms = float(np.sqrt(np.mean(seg * seg)) + 1e-9)
    return peak >= 0.6 * top and peak / rms > 3.0


def apply_claps(segs: list[dict]) -> tuple[list[dict], int]:
    out, dropped = [], 0
    for sg in segs:
        if sg["clap"]:
            if out:
                out.pop()["dropped"] = True
                dropped += 1
        else:
            out.append(sg)
    return out, dropped


def render_clip(x: np.ndarray, s: float, e: float, out: Path) -> float:
    a = max(0, int((s - 0.04) * SR))
    b = min(len(x), int((e + 0.08) * SR))
    clip = x[a:b].astype(np.float64)
    fade = int(0.015 * SR)
    if len(clip) > 2 * fade:
        clip[:fade] *= np.linspace(0, 1, fade)
        clip[-fade:] *= np.linspace(1, 0, fade)
    rms = np.sqrt(np.mean(clip * clip)) + 1e-9
    gain = 10 ** (-18 / 20) / rms  # speech RMS ~ -18 dBFS
    peak = np.max(np.abs(clip)) * gain
    if peak > 0.89:  # -1 dBFS
        gain *= 0.89 / peak
    clip = clip * gain
    clip = np.concatenate([np.zeros(int(0.12 * SR)), clip, np.zeros(int(0.30 * SR))]).astype(np.float32)
    out.parent.mkdir(parents=True, exist_ok=True)
    r = subprocess.run([ffmpeg(), "-v", "error", "-y", "-f", "f32le", "-ar", str(SR), "-ac", "1", "-i", "-",
                        "-af", EQ, "-c:a", "libmp3lame", "-b:a", "96k", str(out)],
                       input=clip.tobytes(), capture_output=True)
    if r.returncode:
        die(f"ffmpeg encode failed: {r.stderr.decode(errors='replace')[:300]}")
    return len(clip) / SR


def preview_png(takes: list[tuple[str, np.ndarray, list[dict], float]], labels: list[str], out: Path) -> None:
    from PIL import Image, ImageDraw
    W, H = 1600, 150
    img = Image.new("RGB", (W, H * len(takes)), (16, 12, 28))
    d = ImageDraw.Draw(img)
    k = 0
    for t, (name, x, segs, thr) in enumerate(takes):
        y0 = t * H
        dur = len(x) / SR or 1
        db = frames_db(x)
        cols = np.array_split(db, W)
        for c, chunk in enumerate(cols):
            v = float(np.max(chunk)) if len(chunk) else -100
            h = int(max(0, (v + 60) / 60) * (H - 40))
            d.line([(c, y0 + H - 20 - h), (c, y0 + H - 20)], fill=(90, 200, 255))
        ty = y0 + H - 20 - int(max(0, (thr + 60) / 60) * (H - 40))
        d.line([(0, ty), (W, ty)], fill=(120, 80, 120))
        for sg in segs:
            xa, xb = int(sg["s"] / dur * W), max(int(sg["e"] / dur * W), int(sg["s"] / dur * W) + 1)
            if sg["clap"]:
                d.rectangle([xa, y0 + 4, xb + 2, y0 + H - 22], outline=(255, 70, 70), width=2)
                d.text((xa, y0 + 4), "CLAP", fill=(255, 90, 90))
            elif sg.get("dropped"):
                d.rectangle([xa, y0 + 18, xb, y0 + H - 22], outline=(140, 140, 140))
                d.text((xa + 2, y0 + 20), "zahozeno", fill=(160, 160, 160))
            else:
                d.rectangle([xa, y0 + 18, xb, y0 + H - 22], outline=(255, 210, 60), width=2)
                lab = labels[k] if k < len(labels) else "?"
                d.text((xa + 2, y0 + 20), lab[:22], fill=(255, 230, 120))
                k += 1
        d.text((6, y0 + H - 16), f"{name}  {dur:.1f}s", fill=(200, 200, 200))
    out.parent.mkdir(parents=True, exist_ok=True)
    img.save(out)


# ---------------------------------------------------------------- ingest

def wire(pack: Path, done: list[dict], lines: dict) -> None:
    qp = pack / "quips.json"
    quips = load_json(qp, [])
    by_id = {q["id"]: q for q in quips}
    for r in done:
        lid, file = r["id"], f"{r['id']}.mp3"
        if r["kind"] == "quip":
            if lid in by_id:
                by_id[lid]["audio"] = file
        else:  # boss line → recorded quip carrying the current text
            text = lines.get(lid, {}).get("text") or r["text"]
            if lid in by_id:
                by_id[lid].update({"text": text, "audio": file})
            else:
                q = {"id": lid, "category": r["kind"], "text": text, "audio": file}
                quips.append(q)
                by_id[lid] = q
    save_json(qp, quips)


def _stamp(p: Path):
    """Sort key: the timestamp in an ElevenLabs download name (…_2026-11-12T16_50_57_…), else the name."""
    m = re.search(r"\d{4}-\d\d-\d\dT\d\d_\d\d_\d\d", p.name)
    return (m.group(0) if m else "~", p.name)


def cmd_ingest(a) -> None:
    pack, vdir = Path(a.pack), Path(a.voice)
    rows = read_csv(vdir / "WAVES.csv")
    if not rows:
        die("WAVES.csv missing: run `plan` first")
    lines = pack_lines(pack)
    files = sorted((Path(f) for f in a.audio), key=_stamp) if a.each else [Path(f) for f in a.audio]
    for f in files:
        if not f.exists():
            die(f"{f} not found")
    all_ids = {r["id"]: r for r in rows}
    single = not a.each and all(f.stem in all_ids for f in files)
    who = a.who or "ty"
    plan, takes, segs_all = [], [], []

    if single:
        for f in files:
            x = decode(f)
            segs, thr = detect(x, a.gap)
            segs, _ = apply_claps(segs)
            if not segs:
                die(f"{f.name}: no speech found")
            s, e = segs[0]["s"], segs[-1]["e"]  # whole line incl. dramatic pauses
            plan.append((all_ids[f.stem], x, s, e))
            takes.append((f.name, x, [{"s": s, "e": e, "clap": False}], thr))
        labels = [p[0]["id"] for p in plan]
    else:
        if not a.wave:
            die("--wave is required for long takes (or name files <id>.mp3)")
        wrows = [r for r in rows if r["wave"].upper() == a.wave.upper()]
        if not wrows:
            die(f"wave {a.wave} not in WAVES.csv")
        if a.only:
            want = [i.strip() for i in a.only.split(",") if i.strip()]
            idx = {r["id"]: r for r in wrows}
            missing = [i for i in want if i not in idx]
            if missing:
                die(f"not in {a.wave}: {', '.join(missing)}")
            targets = [idx[i] for i in want]
        else:
            targets = [r for r in wrows if int(r["order"]) >= a.start]
        speech = []
        for f in files:
            x = decode(f)
            segs, thr = detect(x, a.gap)
            if a.each:  # one file = one line (ElevenLabs downloads): keep everything from first to last sound
                body, _ = apply_claps(segs)
                if not body:
                    die(f"{f.name}: no speech found")
                one = {"s": body[0]["s"], "e": body[-1]["e"], "clap": False}
                takes.append((f.name, x, [one], thr))
                speech.append((x, one))
                continue
            kept, dropped = apply_claps(segs)
            takes.append((f.name, x, segs, thr))
            speech += [(x, sg) for sg in kept]
            print(f"{f.name}: {len(x) / SR:.1f}s, {len(kept)} lines, {dropped} clapped away")
        labels = [t["id"] for t in targets]
        if len(speech) != len(targets) and not (a.partial and len(speech) < len(targets)):
            preview_png(takes, labels, vdir / "_preview" / f"{a.wave}.png")
            report_mismatch(speech, targets)
            die(f"found {len(speech)} lines, wave {a.wave} expects {len(targets)} from #{targets[0]['order'] if targets else '?'}"
                " (use --start / --only / --partial, or --gap)")
        for (x, sg), r in zip(speech, targets):
            plan.append((r, x, sg["s"], sg["e"]))

    # report
    print(f"\n{'#':>3}  {'id':28} {'secs':>5} {'expect':>6}  check")
    warn = 0
    for r, x, s, e in plan:
        dur, exp = e - s, est_secs(r["text"])
        ratio = dur / exp
        flag = "" if 0.45 <= ratio <= 2.6 else ("KRÁTKÉ?" if ratio < 0.45 else "DLOUHÉ?")
        warn += bool(flag)
        print(f"{r['order']:>3}  {r['id']:28} {dur:5.1f} {exp:6.1f}  {flag}")
    preview = vdir / "_preview" / f"{(a.wave or 'single')}.png"
    preview_png(takes, labels, preview)
    print(f"\npreview: {preview}" + (f"  ({warn} lines look off, listen to them)" if warn else ""))
    if a.dry_run:
        print("dry run: nothing written")
        return

    adir = pack / "audio"
    total = 0.0
    for r, x, s, e in plan:
        total += render_clip(x, s, e, adir / f"{r['id']}.mp3")
    wire(pack, [p[0] for p in plan], lines)
    stamp = f"{who} {date.today().isoformat()}"
    done = {p[0]["id"] for p in plan}
    for r in rows:
        if r["id"] in done:
            r["status"] = stamp
    write_csv(vdir / "WAVES.csv", rows)
    print(f"wrote {len(plan)} clips ({total / 60:.1f} min) to {adir}/, wired quips.json, WAVES.csv status = '{stamp}'")
    print("tip: re-run `plan` to tick the lines in waves/*.md")


def report_mismatch(speech, targets) -> None:
    print("\nsegment vs expected length (the first big jump is usually where it went wrong):")
    for k in range(max(len(speech), len(targets))):
        got = f"{speech[k][1]['e'] - speech[k][1]['s']:5.1f}s" if k < len(speech) else "   --"
        exp = f"{est_secs(targets[k]['text']):5.1f}s {targets[k]['id']}" if k < len(targets) else "   --"
        print(f"  {k + 1:3}  got {got}   expected {exp}")


# ---------------------------------------------------------------- status

def cmd_status(a) -> None:
    pack, vdir = Path(a.pack), Path(a.voice)
    rows = read_csv(vdir / "WAVES.csv")
    if not rows:
        die("WAVES.csv missing: run `plan` first")
    adir = pack / "audio"
    waves = {}
    for r in rows:
        w = waves.setdefault(r["wave"], {"n": 0, "done": 0, "stale": 0, "generic": 0})
        w["n"] += 1
        w["generic"] += r["scope"] == "generic"
        if r["status"].startswith("ZMĚNA"):
            w["stale"] += 1
        elif r["status"] and (adir / f"{r['id']}.mp3").exists():
            w["done"] += 1
    tn = sum(w["n"] for w in waves.values())
    td = sum(w["done"] for w in waves.values())
    for k, w in waves.items():
        bar = "#" * round(20 * w["done"] / w["n"]) if w["n"] else ""
        extra = f"  {w['stale']} changed" if w["stale"] else ""
        print(f"{k:5} {w['done']:3}/{w['n']:<3} [{bar:20}]  generic {w['generic']}{extra}")
    mb = sum(f.stat().st_size for f in adir.glob("*.mp3")) / 1048576 if adir.exists() else 0
    print(f"total {td}/{tn} recorded, {mb:.1f} MB in {adir}/")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    for name in ("plan", "ingest", "status"):
        p = sub.add_parser(name)
        p.add_argument("--pack", required=True)
        p.add_argument("--voice", required=True)
        if name == "ingest":
            p.add_argument("audio", nargs="+")
            p.add_argument("--wave")
            p.add_argument("--start", type=int, default=1)
            p.add_argument("--only")
            p.add_argument("--who", choices=["ty", "klon"])
            p.add_argument("--gap", type=float, default=1.6)
            p.add_argument("--partial", action="store_true")
            p.add_argument("--each", action="store_true", help="every file is one line, sorted by the timestamp in its name")
            p.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()
    {"plan": cmd_plan, "ingest": cmd_ingest, "status": cmd_status}[a.cmd](a)


if __name__ == "__main__":
    main()
